"""Pinned MITRE ATT&CK technique catalog + revoked-by resolution.

Generated by ``python -m evals.golden.build_attack_catalog`` from official
STIX 2.1 bundles (enterprise / mobile / ICS). The compact JSON is vendored
so CI stays offline; do not commit the full STIX files.
"""
from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path
from typing import Any

RAW_DIR = Path(__file__).with_name("raw")
TECHNIQUES_PATH = RAW_DIR / "attack_techniques_min.json"
REVOKED_BY_PATH = RAW_DIR / "attack_revoked_by.json"
REVISION_PATH = RAW_DIR / "attack_REVISION.json"

_TECH_ID_RE = re.compile(r"^T\d{4}(?:\.\d{3})?$", re.IGNORECASE)


def _norm_tid(raw: Any) -> str | None:
    if raw is None:
        return None
    s = str(raw).strip()
    if not s:
        return None
    s = s.split()[0].upper()
    if _TECH_ID_RE.fullmatch(s):
        return s
    m = re.search(r"T\d{4}(?:\.\d{3})?", s, re.IGNORECASE)
    if not m:
        return None
    s = m.group(0).upper()
    return s if _TECH_ID_RE.fullmatch(s) else None


@lru_cache(maxsize=1)
def load_revoked_by() -> dict[str, str]:
    """Map revoked technique ID → current replacement ID (already chained)."""
    if not REVOKED_BY_PATH.is_file():
        return {}
    try:
        data = json.loads(REVOKED_BY_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    if not isinstance(data, dict):
        return {}
    out: dict[str, str] = {}
    for src, dst in data.items():
        sid = _norm_tid(src)
        did = _norm_tid(dst)
        if sid and did and sid != did:
            out[sid] = did
    return out


@lru_cache(maxsize=1)
def load_current_techniques() -> tuple[dict[str, Any], ...]:
    """Current (non-revoked) techniques: id, name, description, + metadata."""
    if not TECHNIQUES_PATH.is_file():
        return ()
    try:
        data = json.loads(TECHNIQUES_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return ()
    if not isinstance(data, list):
        return ()
    cleaned: list[dict[str, Any]] = []
    seen: set[str] = set()
    for row in data:
        if not isinstance(row, dict):
            continue
        tid = _norm_tid(row.get("id"))
        if not tid or tid in seen:
            continue
        seen.add(tid)
        parent = _norm_tid(row.get("parent_id")) if "." in tid else None
        cleaned.append(
            {
                "id": tid,
                "name": str(row.get("name") or "").strip(),
                "description": str(row.get("description") or "").strip(),
                "domain": str(row.get("domain") or "").strip(),
                "is_subtechnique": bool(row.get("is_subtechnique") or ("." in tid)),
                "parent_id": parent or (tid.split(".", 1)[0] if "." in tid else None),
                "deprecated": bool(row.get("deprecated")),
            }
        )
    return tuple(cleaned)


@lru_cache(maxsize=1)
def catalog_ids() -> frozenset[str]:
    return frozenset(t["id"] for t in load_current_techniques())


def resolve_technique_id(raw: Any) -> str | None:
    """Normalize a T-ID and follow ``revoked-by`` to the current ID."""
    tid = _norm_tid(raw)
    if not tid:
        return None
    mapping = load_revoked_by()
    seen: set[str] = set()
    while tid in mapping and tid not in seen:
        seen.add(tid)
        tid = mapping[tid]
    return tid


def load_revision() -> dict[str, Any]:
    if not REVISION_PATH.is_file():
        return {}
    try:
        data = json.loads(REVISION_PATH.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    return data if isinstance(data, dict) else {}


def clear_catalog_caches() -> None:
    """Drop in-memory catalog / revoked-by maps (tests)."""
    load_revoked_by.cache_clear()
    load_current_techniques.cache_clear()
    catalog_ids.cache_clear()
